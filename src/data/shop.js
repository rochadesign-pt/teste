export const minPrice = (p) => Math.min(...p.variants.map((v) => v.price))

const skuIndex = new Map()
products.forEach((p) => p.variants.forEach((v) => skuIndex.set(v.sku, { product: p, variant: v })))
export const bySku = (sku) => skuIndex.get(sku) || null
