// CATÁLOGO ÚNICO — tudo o que se vende é um PRODUTO Shopify.
//
// Consumíveis, equipamentos e serviços partilham exatamente a mesma estrutura
// (a do objeto Product da Storefront API). O que os distingue é:
//   · productType   → 'Consumível' | 'Equipamento' | 'Serviço'
//   · metafields    → campos dinâmicos de cada tipo (namespace.key)
//   · collections   → onde aparecem (os serviços não entram em coleções)
//
// Os serviços são produtos normais, mas "discretos": `seo.hidden = 1` tira-os
// da pesquisa e das coleções, e só aparecem ligados a um equipamento através
// dos metafields `servicos.incluidos` / `servicos.opcionais` (listas de
// referências a VARIANTES de serviço — aqui representadas pelo SKU).
//
// Este ficheiro é a fonte de verdade das páginas /equipamentos e /servicos e
// gera o CSV de importação (scripts/export-shopify-csv.mjs).

// ——— forma de um produto ———
// {
//   handle, title, productType, vendor, tags[], collections[],
//   options: [{ name, values[] }],
//   variants: [{ sku, title, price, compareAtPrice?, options?{}, requiresShipping, taxable }],
//   metafields: { 'namespace.key': valor }
// }

